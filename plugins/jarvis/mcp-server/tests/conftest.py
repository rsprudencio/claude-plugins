    # ── Result helpers ────────────────────────────────────────────────

    def _extract_select_columns(self, sql):
        m = re.search(r"SELECT\s+(.*?)\s+FROM", sql, re.I | re.S)
        if not m:
            return ["id", "document", "metadata"]

        select_part = m.group(1).strip()
        if select_part == "*":
            return ["id", "document", "metadata"]

        cols = []
        for part in select_part.split(","):
            part = part.strip()
            # Skip DISTINCT keyword
            if part.upper().startswith("DISTINCT "):
                part = part[9:].strip()
            # Handle "expr AS alias"
            alias_match = re.search(r"\bAS\s+(\w+)\s*$", part, re.I)
            if alias_match:
                cols.append(alias_match.group(1))
                continue
            # Handle "embedding <=> %s::halfvec" -> "distance"
            if "<=>" in part:
                cols.append("distance")
                continue
            # Simple column name (strip type casts)
            clean = re.sub(r"::\w+", "", part)
            clean = re.sub(r"\(.*?\)", "", clean)
            clean = clean.strip()
            if clean and clean.upper() not in ("DISTINCT",):
                cols.append(clean)

        return cols if cols else ["id", "document", "metadata"]

    def _extract_literal_aliases(self, sql):
        """Extract literal value aliases like 'core' AS _schema from SELECT."""
        literals = {}
        m = re.search(r"SELECT\s+(.*?)\s+FROM", sql, re.I | re.S)
        if m:
            for part in m.group(1).split(","):
                part = part.strip()
                lit_match = re.search(r"'(\w+)'\s+AS\s+(\w+)\s*$", part, re.I)
                if lit_match:
                    literals[lit_match.group(2)] = lit_match.group(1)
        return literals

    # ── SQL parsing helpers ───────────────────────────────────────────

    def _extract_column_conditions(self, sql, params):
        """Extract column-based conditions from WHERE clause for core.memories."""
        conditions = []
        param_idx = 0

        # Match column conditions: column = %s, column >= %s
        # (?<!%) prevents matching 's' from '%s' as a column name
        for m in re.finditer(
            r"(?:AND\s+)?(?<!%)(\w+)\s*(=|>=|LIKE)\s*(%s|'([^']*)')",
            sql,
        ):
            col = m.group(1).lower()
            op = m.group(2)
            # Skip 'id' conditions (handled separately) and embedding params
            if col in ("id", "embedding"):
                continue
            if m.group(3) == "%s":
                if param_idx < len(params):
                    value = params[param_idx]
                    param_idx += 1
                else:
                    continue
            else:
                value = m.group(4)
            conditions.append((col, op, value))

        # Also check for metadata JSONB conditions (backward compat)
        for m in re.finditer(
            r"metadata->>'(\w+)'\)?(?:::float)?\s*(=|>=|LIKE)\s*(%s|'([^']*)')",
            sql,
        ):
            key = m.group(1)
            op = m.group(2)
            if m.group(3) == "%s":
                if param_idx < len(params):
                    value = params[param_idx]
                    param_idx += 1
                else:
                    continue
            else:
                value = m.group(4)
            # Route to metadata sub-dict
            conditions.append(("_meta_" + key, op, value))

        # Generic JSONB: metadata->>%s = %s (parameterized key and value)
        for m in re.finditer(
            r"metadata->>%s\s*(=|>=|LIKE)\s*%s",
            sql,
        ):
            op = m.group(1)
            if param_idx + 1 < len(params):
                key = params[param_idx]
                value = params[param_idx + 1]
                param_idx += 2
                conditions.append(("_meta_" + key, op, value))

        return conditions

    def _extract_vault_conditions(self, sql, params):
        """Extract column-based conditions from WHERE clause for vault.documents."""
        conditions = []
        param_idx = 0

        for m in re.finditer(
            r"(?:AND\s+)?(\w+)\s*(=|>=|LIKE)\s*(%s|'([^']*)')",
            sql,
        ):
            col = m.group(1).lower()
            op = m.group(2)
            if col in ("id", "embedding"):
                continue
            if m.group(3) == "%s":
                if param_idx < len(params):
                    value = params[param_idx]
                    param_idx += 1
                else:
                    continue
            else:
                value = m.group(4)
            conditions.append((col, op, value))

        return conditions

    def _extract_order_by(self, sql):
        # ORDER BY column ASC/DESC (but not 'distance')
        m = re.search(r"ORDER BY\s+(\w+)\s+(ASC|DESC)", sql, re.I)
        if m and m.group(1).lower() not in ("distance",):
            return (m.group(1), m.group(2).upper())
        return None

    def _extract_limit(self, sql, params, param_offset):
        if re.search(r"LIMIT\s+%s", sql, re.I):
            if param_offset < len(params):
                try:
                    return int(params[param_offset])
                except (ValueError, TypeError):
                    pass
        m = re.search(r"LIMIT\s+(\d+)", sql, re.I)
        if m:
            return int(m.group(1))
        return None


