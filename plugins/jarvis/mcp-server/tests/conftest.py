def _detect_table(sql):
    """Detect which table a SQL statement targets.

    Dual-compatible: matches both old (core/vault) and new (local/obsidian) schema names.
    Returns: 'core', 'core_active', 'vault', 'meta', 'sync_queue', or 'unknown'
    """
    sql_upper = sql.upper()
    if "LOCAL.ACTIVE_MEMORIES" in sql_upper or "CORE.ACTIVE_MEMORIES" in sql_upper:
        return "core_active"
    if "LOCAL.SYNC_QUEUE" in sql_upper or "CORE.SYNC_QUEUE" in sql_upper:
        return "sync_queue"
    if "LOCAL.MEMORIES" in sql_upper or "CORE.MEMORIES" in sql_upper:
        return "core"
    if "OBSIDIAN.DOCUMENTS" in sql_upper or "VAULT.DOCUMENTS" in sql_upper:
        return "vault"
    if "LOCAL.META" in sql_upper or "CORE.META" in sql_upper:
        return "meta"
    # Legacy fallback
    if "JARVIS_META" in sql_upper:
        return "meta"
    if "FROM JARVIS" in sql_upper or "INTO JARVIS" in sql_upper or "UPDATE JARVIS" in sql_upper:
        return "core"
    return "unknown"


class MockCursor:
    """Translates SQL patterns from production code into InMemoryDB operations.

    Routes queries to the correct table (core.memories, vault.documents,
    core.meta) based on SQL pattern matching.
    """

    def __init__(self, db: InMemoryDB):
        self.db = db
        self._rows = []
        self._description = None
        self.rowcount = 0

    @property
    def description(self):
        return self._description

    def execute(self, sql, params=None):
        params = tuple(params) if params else ()
        sql_norm = " ".join(sql.split())
        sql_upper = sql_norm.upper()

        # Schema DDL — no-op
        if any(sql_upper.startswith(kw) for kw in ("CREATE ", "DO ", "ALTER ")):
            self._description = None
            return

        # pg_extension check — no-op
        if "PG_EXTENSION" in sql_upper:
            self._description = [_Col("extversion")]
            self._rows = [("0.8.0",)]
            return

        # Advisory lock — no-op
        if "PG_ADVISORY" in sql_upper:
            self._description = None
            return

        # to_regclass check
        if "TO_REGCLASS" in sql_upper:
            self._description = [_Col("to_regclass")]
            self._rows = [(None,)]  # fresh install by default
            return

        table = _detect_table(sql_norm)

        # INSERT
        if sql_upper.lstrip().startswith("INSERT"):
            if table == "meta":
                self._handle_meta_insert(sql_norm, params)
            elif table == "vault":
                self._handle_vault_insert(sql_norm, params)
            else:
                self._handle_core_insert(sql_norm, params)
            return

        # UPDATE
        if sql_upper.lstrip().startswith("UPDATE"):
            self._handle_core_update(sql_norm, params)
            return

        # DELETE
        if sql_upper.lstrip().startswith("DELETE"):
            if table == "vault":
                self._handle_vault_delete(sql_norm, params)
            else:
                self._handle_core_delete(sql_norm, params)
            return

        # SELECT
        if sql_upper.lstrip().startswith("SELECT"):
            if table == "meta":
                self._handle_meta_select(sql_norm, params)
            elif table in ("vault",):
                self._handle_vault_select(sql_norm, params)
            elif table in ("core", "core_active"):
                active_only = table == "core_active"
                self._handle_core_select(sql_norm, params, active_only)
            else:
                # Try to route by context
                if "PG_TOTAL_RELATION_SIZE" in sql_upper:
                    self._description = [_Col("total_bytes")]
                    self._rows = [(0,)]
                else:
                    self._handle_core_select(sql_norm, params, False)
            return

        # Unknown — no-op
        self._description = None
        self._rows = []
        self.rowcount = 0

    def executemany(self, sql, params_list):
        count = 0
        for p in params_list:
            self.execute(sql, p)
            count += self.rowcount
        self.rowcount = count

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return list(self._rows)

    # ── Core INSERT handler ────────────────────────────────────────────

    def _handle_core_insert(self, sql, params):
        """INSERT INTO core.memories (...) VALUES (...) ON CONFLICT DO UPDATE."""
        sql_upper = sql.upper()

        # Detect column list from SQL
        col_match = re.search(r"INSERT INTO\s+\S+\s*\(([^)]+)\)", sql, re.I)
        if not col_match:
            # Fallback: legacy pattern (id, document, embedding, metadata, ...)
            self._handle_legacy_insert(sql, params)
            return

        cols = [c.strip().lower() for c in col_match.group(1).split(",")]

        # Parse VALUES clause to handle literal values vs %s placeholders
        vals_match = re.search(r"VALUES\s*\(([^)]+)\)", sql, re.I)
        if vals_match:
            val_tokens = [v.strip() for v in vals_match.group(1).split(",")]
            param_idx = 0
            vals = []
            for token in val_tokens:
                # Strip type casts like ::halfvec, ::jsonb
                clean = re.sub(r"::\w+", "", token).strip()
                if clean == "%s":
                    vals.append(params[param_idx] if param_idx < len(params) else None)
                    param_idx += 1
                else:
                    # Literal value in SQL (e.g. 0.0, 'active')
                    literal = clean.strip("'\"")
                    try:
                        literal = float(literal)
                    except (ValueError, TypeError):
                        pass
                    vals.append(literal)
        else:
            vals = list(params[:len(cols)])

        row_data = dict(zip(cols, vals))
        row_id = row_data.get("id", "")
        document = row_data.get("document", "")
        embedding = row_data.get("embedding", [])
        category = row_data.get("category", "observation")
        scope = row_data.get("scope", "global")
        project = row_data.get("project")
        source = row_data.get("source", "auto-extract")
        importance_score = float(row_data.get("importance_score", 0.5))
        retrieval_count = float(row_data.get("retrieval_count", 0.0))
        metadata_json = row_data.get("metadata", "{}")
        created_at = row_data.get("created_at")
        updated_at = row_data.get("updated_at")

        if isinstance(metadata_json, str):
            metadata = json.loads(metadata_json)
        elif isinstance(metadata_json, dict):
            metadata = dict(metadata_json)
        else:
            metadata = {}

        self.db.upsert_core(
            row_id, document, embedding,
            category=category, scope=scope, project=project,
            source=source, importance_score=importance_score,
            retrieval_count=retrieval_count, metadata=metadata,
            created_at=created_at, updated_at=updated_at,
        )
        self.rowcount = 1
        self._description = None
        self._rows = []

    def _handle_legacy_insert(self, sql, params):
        """Fallback for old-style INSERT INTO jarvis (id, doc, emb, meta, ...)."""
        row_id = params[0]
        document = params[1]
        embedding = params[2]
        metadata_json = params[3]
        created_at = params[4] if len(params) > 4 else None
        updated_at = params[5] if len(params) > 5 else None
        self.db.upsert(row_id, document, embedding, metadata_json, created_at, updated_at)
        self.rowcount = 1
        self._description = None
        self._rows = []

    # ── Vault INSERT handler ────────────────────────────────────────────

    def _handle_vault_insert(self, sql, params):
        """INSERT INTO vault.documents (...) VALUES (...) ON CONFLICT DO UPDATE."""
        col_match = re.search(r"INSERT INTO\s+\S+\s*\(([^)]+)\)", sql, re.I)
        if not col_match:
            return

        cols = [c.strip().lower() for c in col_match.group(1).split(",")]
        vals = list(params[:len(cols)])

        row_data = dict(zip(cols, vals))
        row_id = row_data.get("id", "")
        document = row_data.get("document", "")
        embedding = row_data.get("embedding", [])
        parent_file = row_data.get("parent_file", "")
