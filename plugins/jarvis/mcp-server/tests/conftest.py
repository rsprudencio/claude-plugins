    def delete_vault_where(self, key, value):
        """Delete vault rows where a column matches a value."""
        to_delete = [
            rid for rid, row in self.vault_rows.items()
            if row.get(key) == value
        ]
        for rid in to_delete:
            del self.vault_rows[rid]
        return len(to_delete)

    def _filter_rows(self, store, conditions=None, active_only=False):
        """Filter rows from a store with column-based conditions.

        Keys prefixed with '_meta_' are resolved from row['metadata'] sub-dict
        (e.g., '_meta_session_id' looks up row['metadata']['session_id']).
        """
        rows = list(store.values())
        if active_only:
            rows = [r for r in rows if r.get("status") == "active"]
        if not conditions:
            return rows
        for key, op, value in conditions:
            # Resolve _meta_ prefixed keys from metadata sub-dict
            if key.startswith("_meta_"):
                meta_key = key[6:]  # strip '_meta_' prefix
                def _get_val(r, mk=meta_key):
                    return r.get("metadata", {}).get(mk, "")
            else:
                def _get_val(r, k=key):
                    return r.get(k, "")

            if op == "=":
                val_cmp = value if isinstance(value, str) else str(value)
                rows = [r for r in rows if str(_get_val(r)) == val_cmp]
            elif op == ">=":
                try:
                    fval = float(value)
                    rows = [r for r in rows if float(_get_val(r) or 0) >= fval]
                except (ValueError, TypeError):
                    pass
            elif op == "LIKE":
                pattern = re.escape(str(value)).replace(r"\%", ".*")
                rows = [
                    r for r in rows
                    if re.search(pattern, str(_get_val(r)))
                ]
        return rows

    def list_core(self, conditions=None, order_by=None, limit=None, active_only=False):
        rows = [dict(r) for r in self._filter_rows(self.core_rows, conditions, active_only)]
        if order_by:
            field, direction = order_by
            reverse = direction == "DESC"
            def sort_key(r):
                val = r.get(field)
                if field in ("created_at", "updated_at"):
                    return val or ""
                try:
                    return float(val) if val is not None else 0.0
                except (ValueError, TypeError):
                    return 0.0
            try:
                rows.sort(key=sort_key, reverse=reverse)
            except (ValueError, TypeError):
                pass
        if limit:
            rows = rows[:limit]
        return rows

    def list_vault(self, conditions=None, order_by=None, limit=None):
        rows = [dict(r) for r in self._filter_rows(self.vault_rows, conditions)]
        if order_by:
            field, direction = order_by
            reverse = direction == "DESC"
