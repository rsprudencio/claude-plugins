def _cosine_distance(a, b):
    """Cosine distance: 0 = identical, 2 = opposite."""
    if not a or not b:
        return 1.0
    min_len = min(len(a), len(b))
    a, b = a[:min_len], b[:min_len]
    dot = sum(x * y for x, y in zip(a, b))
    norm_a = math.sqrt(sum(x * x for x in a))
    norm_b = math.sqrt(sum(x * x for x in b))
    if norm_a == 0 or norm_b == 0:
        return 1.0
    return max(0.0, 1.0 - (dot / (norm_a * norm_b)))


class InMemoryDB:
    """In-memory mock for the jarvis PostgreSQL table.

    Stores documents as dicts: {id, document, embedding, metadata, created_at, updated_at}.
    Metadata is always a Python dict (like psycopg's auto-deserialized JSONB).
    """

    def __init__(self):
        self.rows = {}  # id -> row dict
        self.meta_rows = {}  # key -> {key, value, updated_at}

    def upsert(self, row_id, document, embedding, metadata_json, created_at=None, updated_at=None):
        now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        if isinstance(metadata_json, str):
            meta = json.loads(metadata_json)
        elif isinstance(metadata_json, dict):
            meta = dict(metadata_json)
        else:
            meta = {}

        existing = self.rows.get(row_id)
        self.rows[row_id] = {
            "id": row_id,
            "document": document,
            "embedding": embedding if isinstance(embedding, list) else list(embedding or []),
            "metadata": meta,
            "created_at": created_at or (existing["created_at"] if existing else now),
            "updated_at": updated_at or now,
        }

    def get(self, row_id):
        row = self.rows.get(row_id)
        return dict(row) if row else None

    def get_many(self, ids):
        return [dict(self.rows[rid]) for rid in ids if rid in self.rows]

    def delete(self, row_id):
        return self.rows.pop(row_id, None) is not None

    def delete_where_metadata(self, key, value):
        to_delete = [
            rid for rid, row in self.rows.items()
            if row["metadata"].get(key) == value
        ]
        for rid in to_delete:
            del self.rows[rid]
        return len(to_delete)

    def count(self, conditions=None):
        return len(self._filter(conditions))

    def _filter(self, conditions=None):
        rows = list(self.rows.values())
        if not conditions:
            return rows
        for key, op, value in conditions:
            if op == "=":
                # Compare directly — avoids str(Enum) producing qualified name
                # (e.g. str(ContentType.OBSERVATION) → "ContentType.OBSERVATION"
                #  but json-stored value is "observation")
                val_cmp = value if isinstance(value, str) else str(value)
                rows = [r for r in rows if r["metadata"].get(key, "") == val_cmp]
            elif op == ">=":
                try:
                    fval = float(value)
                    rows = [r for r in rows if float(r["metadata"].get(key, 0)) >= fval]
                except (ValueError, TypeError):
                    pass
            elif op == "LIKE":
                pattern = re.escape(str(value)).replace(r"\%", ".*")
                rows = [
                    r for r in rows
                    if re.search(pattern, str(r["metadata"].get(key, "")))
                ]
        return rows

    def list_filtered(self, conditions=None, order_by=None, limit=None):
        rows = [dict(r) for r in self._filter(conditions)]
        if order_by:
            field, direction = order_by
            reverse = direction == "DESC"

            def sort_key(r):
                if field in ("created_at", "updated_at"):
                    return r.get(field, "")
                return float(r["metadata"].get(field, 0))

            try:
                rows.sort(key=sort_key, reverse=reverse)
            except (ValueError, TypeError):
                pass
        if limit:
            rows = rows[:limit]
        return rows

    def vector_search(self, query_embedding, limit, conditions=None):
        rows = [dict(r) for r in self._filter(conditions)]
        for r in rows:
            r["distance"] = _cosine_distance(query_embedding, r.get("embedding", []))
        rows.sort(key=lambda r: r["distance"])
        return rows[:limit]

    def clear(self):
        self.rows.clear()
        self.meta_rows.clear()


