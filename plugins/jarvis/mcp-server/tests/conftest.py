    # ── Core SELECT handler ────────────────────────────────────────────

    def _handle_core_select(self, sql, params, active_only=False):
        sql_upper = sql.upper()

        # pg_total_relation_size
        if "PG_TOTAL_RELATION_SIZE" in sql_upper:
            self._description = [_Col("total_bytes")]
            self._rows = [(0,)]
            return

        # GROUP BY (collection_stats)
        if "GROUP BY" in sql_upper:
            self._handle_core_group_by(sql, params, active_only)
            return

        # COUNT(*)
        if "COUNT(*)" in sql_upper:
            conditions = self._extract_column_conditions(sql, params)
            rows = self.db._filter_rows(self.db.core_rows, conditions, active_only)
            alias_match = re.search(r"count\(\*\)\s+AS\s+(\w+)", sql, re.I)
            col = alias_match.group(1) if alias_match else "cnt"
            self._description = [_Col(col)]
            self._rows = [(len(rows),)]
            return

        # Vector search (embedding <=>)
        if "embedding <=>" in sql:
            self._handle_core_vector_search(sql, params, active_only)
            return

        # Batch get: ANY(%s)
        if "ANY(" in sql_upper:
            ids = params[0] if params else []
            rows = self.db.get_many_core(ids)
            self._set_core_results(sql, rows)
            return

        # Single get: WHERE id = %s
        if re.search(r"WHERE\s+id\s*=\s*%s", sql, re.I):
            row = self.db.get_core(params[0]) if params else None
            rows = [row] if row else []
            if active_only:
                rows = [r for r in rows if r.get("status") == "active"]
            self._set_core_results(sql, rows)
            return

        # Filtered query (column conditions)
        conditions = self._extract_column_conditions(sql, params)
        order_by = self._extract_order_by(sql)
        limit_val = self._extract_limit(sql, params, len([c for c in conditions]))
        rows = self.db.list_core(conditions, order_by, limit_val, active_only)
        self._set_core_results(sql, rows)

    def _handle_core_vector_search(self, sql, params, active_only=False):
        # In vector search queries the embedding %s appears in the SELECT
        # clause (before WHERE), so it's always params[0].  Column conditions
        # in the WHERE clause consume params[1..N-1], and LIMIT is params[-1].
        query_embedding = params[0] if params else []

        # Extract WHERE conditions using params shifted past the embedding
        conditions = self._extract_column_conditions(sql, params[1:]) if len(params) > 1 else []
        param_offset = 1 + len(conditions)

        limit = 10
        if len(params) > param_offset:
            try:
                limit = int(params[-1])
            except (ValueError, TypeError):
                limit = 10

        results = self.db.vector_search_core(query_embedding, limit, conditions, active_only)

        # Inject _schema for cross-schema query support (dynamic: local or core)
        schema_val = "local" if "LOCAL." in sql.upper() else "core"
        for r in results:
            r["_schema"] = schema_val

        # Build columns from SELECT clause
        cols = self._extract_select_columns(sql)
        if "distance" not in cols:
            cols.append("distance")
        # Resolve literal aliases (e.g., 'core' AS _schema)
        literals = self._extract_literal_aliases(sql)
        self._description = [_Col(c) for c in cols]
        self._rows = [tuple(literals.get(c, r.get(c)) for c in cols) for r in results]

    def _handle_core_group_by(self, sql, params, active_only=False):
        rows = list(self.db.core_rows.values())
        if active_only:
            rows = [r for r in rows if r.get("status") == "active"]

        if "category" in sql.lower():
            groups = Counter(r.get("category", "unknown") for r in rows)
            self._description = [_Col("category"), _Col("cnt")]
            self._rows = [(t, c) for t, c in groups.most_common(20)]
        elif "scope" in sql.lower():
            groups = Counter(r.get("scope", "global") for r in rows)
            self._description = [_Col("scope"), _Col("cnt")]
            self._rows = [(s, c) for s, c in groups.most_common(20)]
        else:
            self._description = [_Col("key"), _Col("cnt")]
            self._rows = []

    def _set_core_results(self, sql, rows):
        cols = self._extract_select_columns(sql)
        if not cols:
            cols = ["id", "document", "metadata"]
        self._description = [_Col(c) for c in cols]
        self._rows = [tuple(r.get(c) for c in cols) for r in rows]

