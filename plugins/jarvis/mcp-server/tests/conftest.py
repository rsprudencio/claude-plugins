class MockEmbeddingService:
    """Returns deterministic 384d vectors based on text content hash.

    Similar texts produce similar vectors (via SHA-256 hash),
    enabling realistic vector search in tests.
    """

    def __init__(self, dimensions=384):
        self._dimensions = dimensions

    def encode(self, text: str) -> list[float]:
        h = hashlib.sha256(text.encode()).digest()
        vec = [(h[i % len(h)] / 255.0) * 2 - 1 for i in range(self._dimensions)]
        norm = math.sqrt(sum(x * x for x in vec))
        return [x / norm for x in vec] if norm > 0 else vec

    def encode_batch(self, texts: list[str], batch_size: int = 64) -> list[list[float]]:
        return [self.encode(t) for t in texts]

    @property
    def dimensions(self) -> int:
        return self._dimensions

    @property
    def model_name(self) -> str:
        return "mock-model"

    @property
    def backend(self) -> str:
        return "mock"

    @property
    def is_loaded(self) -> bool:
        return True


